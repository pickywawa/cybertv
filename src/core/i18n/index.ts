const dicts: Record<Lang, Record<I18nKey, string>> = { fr, en };
let current: Lang = 'fr';

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
}
export function getLang(): Lang {
  return current;
}
export const locale = () => (current === 'fr' ? 'fr-FR' : 'en-GB');

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[current][key] ?? fr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function fmtTime(ts: number): string {
  return new Date(ts).toLocaleTimeString(locale(), { hour: '2-digit', minute: '2-digit' }).replace(':', current === 'fr' ? 'h' : ':');
}
export function fmtDate(ts: number, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'long', year: 'numeric' }): string {
  return new Date(ts).toLocaleDateString(locale(), opts);
}
export function fmtDuration(sec: number): string {
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  const s = Math.floor(sec % 60);
  return h ? `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}` : `${m}:${String(s).padStart(2, '0')}`;
}
export function fmtRuntime(sec: number): string {
  const h = Math.floor(sec / 3600);
  const m = Math.round((sec % 3600) / 60);
  return h ? `${h} h ${String(m).padStart(2, '0')}` : `${m} min`;
}
